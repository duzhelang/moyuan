       (SELECT COUNT(*) FROM `poem` o WHERE o.`poet_id` = p.`id` AND o.`deleted` = 0) AS works,
       `deleted`
FROM `poet` p WHERE `id` IN (1, 6, 448) ORDER BY `id`;

SELECT '认证' AS kind, u.`id` AS user_id, u.`username`, u.`nickname`, u.`poet_verified`,
       pr.`pen_name`, pr.`real_name`, pr.`verified_status`, pr.`work_count`, pr.`like_count`, pr.`follower_count`
FROM `user` u LEFT JOIN `poet_profile` pr ON pr.`id` = u.`poet_profile_id`
WHERE u.`username` IN ('senyao', 'biwang');
